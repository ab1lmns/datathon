DRINKING='Система отметила питьё на рабочем месте. Этот сигнал не подтверждает наличие денег рядом, принадлежность чашки работнику или нарушение правил хранения личных вещей.'

def qualify_known_description(code, description):
    if code not in REGISTRY or not isinstance(description,str): return description
    templates=[(REGISTRY[code]['template'],WORDING[code])]
    templates += [(tpl,DRINKING if kind=='drinking' else WORDING[code])
                  for (typ,kind),tpl in VARIANTS.items() if typ==code]
    for template,replacement in templates:
        pattern=re.escape(template).replace(re.escape('{t:.1f}'),r'\d+\.\d+')
        match=re.match(pattern,description)
        if match:
            return replacement+description[match.end():]
    return description
